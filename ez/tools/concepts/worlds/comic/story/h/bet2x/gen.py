#!/usr/bin/env python3
"""bet2x: builds x2p_bet.js/.css (an X2+ drop-in) from X3+'s live bet, ez/tools/v22/story/h_bet.* and h_betd.* (read only).
Every change to the X3+ sources is a listed, asserted text patch, so a later change to X3+'s bet is ported by rerunning: python3 gen.py"""
import os,re
H=os.path.dirname(os.path.abspath(__file__));S=os.path.normpath(H+'/../../../../../../v22/story')
rd=lambda f:open(os.path.join(S,f)).read()
def sub(s,a,b,n=1):
    c=s.count(a);assert c==n,(a,c,n);return s.replace(a,b)
# --- JS: h_bet.js (the vault, headline, chip timer, parts list, ALIVE) ---
bj=rd('h_bet.js')
bj=sub(bj,"""function dress(){const sec=D.querySelector('#wc-book .wc-bet');""","""function dress(){const sec=D.querySelector('#x2pSt');""")
bj=sub(bj,"""sec.classList.add('hb-on');""","""sec.classList.add('hb-on');H.classList.add('x2b-on');sec.setAttribute('aria-labelledby','x2bH');""")
bj=sub(bj,"""<h2 class="hb-h">""","""<h2 class="hb-h" id="x2bH">""")
bj=sub(bj,"""(function wait(n){if(H.classList.contains('p1-on')&&!H.classList.contains('cd-on')&&D.querySelector('#wc-book .wc-bet')&&window.MODELS)start();""",
 """(function wait(n){if(D.querySelector('#x2pSt')&&window.MODELS&&window.__x2pPnl)start();""")
bj=sub(bj,".wc-bet.hb-on ","#x2pSt.hb-on ",n=3)
# --- JS: h_betd.js (board D: the flow into the pool, the fork, Season 2) ---
dj=rd('h_betd.js')
dj=sub(dj,"""if(!H.classList.contains('p1-on')||H.classList.contains('cd-on'))""","""if(!H.classList.contains('x2b-on'))""")
dj=sub(dj,"""D.querySelector('#wc-book .wc-bet.hb-on')""","""D.querySelector('#x2pSt.hb-on')""")
# start order as on X3+: there h_betd's first try comes on a 150 ms timer, after h_bet has placed the chip (and re-placed it on fonts.ready)
# at the un-bled width; run synchronously here it would add .bd-on first and the chip would be placed bled (a different crop than live X3+)
dj=sub(dj,"try{go(0)}catch(e){window.__x2pBdErr=e;console.error(e)}","setTimeout(()=>{try{go(0)}catch(e){window.__x2pBdErr=e;console.error(e)}},150)")
# the comic's fonts at the weights X3+ asks for (Shantell Sans 800 on the die labels and board words; X2+ loads 600;700 only)
FONT="""/* X2+ loads Shantell Sans at 600;700 only: ask for X3+'s own set (400, 600, 800, italic 600), so the bet draws exactly as on X3+ */
(function(){var D=document;if(D.getElementById('x2b-font'))return;var l=D.createElement('link');l.id='x2b-font';l.rel='stylesheet';
 l.href='https://fonts.googleapis.com/css2?family=Bangers&family=Shantell+Sans:ital,wght@0,400;0,600;0,800;1,600&display=swap';D.head.appendChild(l)})();
"""
HEAD="""/* X2P_BET (bet2x, round H24 addendum 2): X3+'s live bet chapter, Bet #1: NVIDIA, as an X2+ drop-in. Generated by
   tools/concepts/worlds/comic/story/h/bet2x/gen.py from tools/v22/story/h_bet.js + h_betd.js; do not edit by hand, rerun gen.py.
   It mounts in X2+'s own bet section (#x2pSt, built by x2plus.js BETSEC), whose children stay in the DOM, hidden; it needs no comic
   DOM (#wc-book, html.p1-on). Data rules unchanged: the bet time is world-comic.js's betAt (verbatim), the pool share SIM.poolShare,
   the leader the P&L leader of window.__x2pPnl (X3+ reads the same name from its own chapter). html.x2b-on is set once mounted.
   Errors: window.__x2pHbetErr (the chip), window.__x2pBdErr (the board). */
"""
open(H+'/x2p_bet.js','w').write(HEAD+FONT+bj.rstrip()+'\n'+dj)
# --- CSS ---
bc=rd('h_bet.css');dc=rd('h_betd.css')
bc=sub(bc,"html.p1-on .wc-bet.hb-on","html #x2pSt.hb-on",n=bc.count("html.p1-on .wc-bet.hb-on"))
assert 'p1-on' not in bc and 'wc-bet' not in bc,'unported X3+ selector in h_bet.css'
dc=dc.replace("html.p1-on:not(.cd-on)","html.x2b-on")
assert 'p1-on' not in dc and 'wc-bet' not in dc,'unported X3+ selector in h_betd.css'
# X3+ loads Shantell Sans at 400/600/800 only, so its 700 text draws with the 800 face; X2+ also has a real 700 face (x2p_top's link).
# Ask for 800 where X3+ asks for 700, so the words draw exactly as they do live on X3+.
n0=len(re.findall(r"font:700 ([^;]*?)'Shantell Sans'",bc+dc));bc=re.sub(r"font:700 ([^;]*?)'Shantell Sans'",r"font:800 \1'Shantell Sans'",bc);dc=re.sub(r"font:700 ([^;]*?)'Shantell Sans'",r"font:800 \1'Shantell Sans'",dc);assert n0>=5,n0
GEO="""
/* X2+ geometry: the section is sized and centred exactly as X3+'s chapter (its book: 14px gutters, 560px wide below 1000px;
   40px gutters, 1100px wide from 1000px), so every pixel inside it is X3+'s. X2+'s own head, strap and tickets stay, hidden. */
html #x2pSt.hb-on{--x2bw:min(calc(100vw - 28px),532px);box-sizing:border-box;width:var(--x2bw);max-width:none;margin-left:calc((100% - var(--x2bw))/2)!important;margin-right:calc((100% - var(--x2bw))/2)!important;padding:0 0 6px;border:0;background:none;box-shadow:none;transform:none}
html #x2pSt.hb-on .hb-wrap{font:500 15px/20.25px "Shantell Sans","Comic Neue",system-ui,sans-serif;letter-spacing:normal;text-align:left}
@media (min-width:1000px){html #x2pSt.hb-on{--x2bw:min(calc(100vw - 80px),1100px)}}
@media (min-width:1200px){html.x2p-desk #x2pSt.hb-on{grid-column:1/-1}}
/* opt-in, off by default (html.x2b-bleed): addendum 2's "everything bleeds" taken one step past X3+. On phones X3+'s vault, chip and board
   already run edge to edge, but the section's dark ground stops 14px short of each edge; this runs the ground to the edges too. */
@media (max-width:999px){html.x2b-on.x2b-bleed #x2pSt.hb-on .hb-gr{left:calc(50% - 50vw);right:calc(50% - 50vw);filter:none}
 html.x2b-on.x2b-bleed #x2pSt.hb-on .hb-gr i{clip-path:none}html.x2b-on.x2b-bleed #x2pSt.hb-on .hb-gr i::before{inset:0;clip-path:none}}
"""
open(H+'/x2p_bet.css','w').write("/* X2P_BET (bet2x): generated by gen.py from tools/v22/story/h_bet.css + h_betd.css; rerun gen.py, do not edit. */\n"+bc+'\n'+dc+GEO)
print('ok',len(open(H+'/x2p_bet.js').read()),len(open(H+'/x2p_bet.css').read()))
