"""EZ Live X4 skin generator (owner, 2026-10-12: "X2's exact layout in X3's colours").

Rewrites the block between the GENERATED markers in tools/v22/skin-x4.css. Everything outside the markers (the palette
tokens before it, the hand fixes after it) is kept as written. Run it from ez/ after any change to v15-season.html or
tools/v22/routes.css, then rebuild:

    python3 tools/v22/gen-skin-x4.py tools/v22 && python3 tools/v22/build.py tools/v22

What it does, colour only (it never emits a size, radius, spacing, width, offset or font):
  1. reads X2's CSS exactly as build.py composes it (v15-season.html's <style> blocks with routes.css inserted);
  2. for every declaration that draws with the ink colour or a hard-coded light / navy colour, emits a copy with only
     the colour swapped: ink rings and ink borders -> the line colour, ink offset shadows -> near-black, paper and navy
     surfaces -> X3's dark surfaces, dark text -> light text (dark text stays dark on yellow, green and red fills);
  3. copies are written as ":where(html.x4) <original selector>" (or "<root compound>:where(.x4)"), so each copy has the
     original rule's specificity and sits after it in source order: it wins exactly where the original won. Any later
     rule of equal specificity that set the same colour property is copied too (identity if its colour is fine), so
     the cascade between rules is unchanged. Border and outline copies only set *-color longhands, background copies
     only background-color / background-image, so no copy can change geometry.
  4. the text tokens follow the surface: rules whose fill stays bright in X3's palette (yellow, green, red, white logo
     tiles) set dark --ink / --ink2 / --dim / --on-ez / --on-slab and dark text; paper, washes, navy and foil set the
     light ones back; a fill removed again inherits them. X2's selected states (navy pill, white text) become X3's
     pressed state: its raised surface (#222733) with light text; X2's rainbow foil (#1) X3's raised surface with a yellow ring; X2's yellow shimmer (wins) X3's yellow tint
     with a yellow-edged ring (X3: .cg-c.w); X2's colour washes X3's tint strength; X2's sunburst X3's plain surface.
  5. where X3 gives one of X2's elements a colour treatment of its own, X4 takes X3's colours (X3_SAME below), and the
     fee diagram's short connector lines, which X2 fills with ink, take the line colour like the brackets they hang
     from (STEMS below).

Needs tinycss2 (pip install tinycss2), a real CSS tokenizer: comments, strings, @media nesting and nested functions
are handled by it, not by regular expressions.
"""
