def x2_css():
    src = open(os.path.join(EZ, 'v15-season.html')).read()
    css = open(os.path.join(S, 'routes.css')).read()
    i = src.rindex('</style>', 0, src.find('<!--WSJ:') if '<!--WSJ:' in src else len(src))
    src = src[:i] + css + src[i:]
    head = src[:src.index('</head>')]
    return re.findall(r'<style[^>]*>(.*?)</style>', head, re.S)

# ---------------------------------------------------------------- small value helpers (on tinycss2 serialisations)
def split_top(v, sep):
    """split on sep (',' or whitespace) outside brackets and strings"""
    out, d, cur, q = [], 0, '', None
    for ch in v:
        if q:
            cur += ch
            if ch == q: q = None
            continue
        if ch in '"\'': q = ch; cur += ch; continue
        if ch in '([': d += 1
        elif ch in ')]': d -= 1
        if d == 0 and ((sep == ',' and ch == ',') or (sep == ' ' and ch.isspace())):
            if sep == ',' or cur: out.append(cur)
            cur = ''
            continue
        cur += ch
    if cur or sep == ',': out.append(cur)
    return [x.strip() for x in out if sep == ',' or x.strip()]

