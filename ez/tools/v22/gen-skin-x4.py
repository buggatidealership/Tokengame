def rule_bg(decls):
    """'y' / 'gr' (stays bright), 'paper' / 'slab' / 'tint' (turns dark), or None"""
    bg = None
    for name, v, imp in decls:
        lh = longhands(name, v)
        if 'background-color' not in lh and 'background-image' not in lh: continue
        c, im = norm(lh.get('background-color', 'transparent')), norm(lh.get('background-image', 'none'))
        if c in BRIGHT_Y: bg = 'y'
        elif c in BRIGHT_GR: bg = 'gr'
        elif c in PAPER: bg = 'paper'
        elif c in SLABS: bg = 'slab'
        elif im == 'var(--win-grad)': bg = 'win'      # X2's yellow shimmer: X3's yellow tint (light text on it)
        elif im == 'var(--foil-grad)': bg = 'foil'    # X2's rainbow foil (#1): X3's raised surface, a yellow ring
        elif im in TINT_IMG or re.match(r'color-mix\(insrgb,var\(--(yel|ez-gold|ez-green|ez-red|red|grn|mc)\)\d+%,var\(--(card|field)\)\)', c):
            bg = 'tint'
        elif c in ('transparent', 'none') and im == 'none':
            bg = 'clear'
        elif c not in ('inherit', 'initial', 'unset', 'currentcolor', 'var(--ink)') and not c.startswith('rgba(0,0,0'):
            bg = 'other'
    return bg

def tint(v):
    """X2's colour washes over paper (14-70%) would turn olive and muddy on X3's dark: X3's tint strength instead"""
    def f(m):
        k, n = m.group(1), int(m.group(2))
        n = 5 if k in ("yel", "ez-gold") else max(8, round(n / 2))
        return 'color-mix(in srgb,var(--%s) %d%%,var(--%s))' % (k, n, m.group(3))
    v = re.sub(r'color-mix\(in srgb,\s*var\(--(yel|ez-gold|ez-green|ez-red|red|grn)\)\s+(\d+)%,\s*var\(--(card|field)\)\)', f, v)
    # the stat panels' key-colour wash (--mc: blue, green, gold, violet at 13-16%) is a heavy cast on X3's dark: 6%
    v = re.sub(r'color-mix\(in srgb,\s*var\(--mc\)\s+\d+%,\s*var\(--(card|field)\)\)', r'color-mix(in srgb,var(--mc) 6%,var(--\1))', v)
    # X2's pale blue panel (the 31% "operations" box): X3 has no blue, its raised surface instead
    return re.sub(r'color-mix\(in srgb,\s*#2f7fe0\s+\d+%,\s*var\(--card\)\)', 'var(--x-s2)', v)

def rays(v):
    """the sunburst on sealed and upcoming rounds: X3 draws a plain raised surface there (skin-x3.css: .sealart),
    so each layer (the disc, the rays) becomes a flat layer of X3's --x-s2; the layer count stays X2's, so the per-layer
    background lists (clip, origin, attachment) are unchanged"""
    if 'repeating-conic-gradient(' not in v: return v
    return ','.join('linear-gradient(var(--x-s2),var(--x-s2))' for _ in split_top(v, ','))

def map_decl(lh, v, ctx):
    """X4 value for one colour longhand, or None when it does not change"""
    n = norm(v)
    if lh == 'box-shadow':
        r = map_shadow(v)
    elif lh == 'text-shadow':
        r = map_text_shadow(v)
    elif lh.endswith('-color') and (lh.startswith('border') or lh.startswith('outline') or lh.startswith('column-rule')):
        r = map_line_colour(v)
    elif lh in ('color', '-webkit-text-fill-color', 'caret-color'):
        if ctx.get('sel'): r = v if n == 'var(--yel)' else TX      # X3's pressed state: light text (yellow stays)
        elif ctx['bright'] and (n in DARK_TEXT or n in ('var(--on-slab)', 'var(--on-slab2)', 'var(--on-slab3)')): r = 'var(--ink)'
        elif ctx.get('chip') and n in ('#fff', '#ffffff', 'white'): r = TX     # white on an ink chip: the chip is X3's #222733
        elif n in ('#fff', '#ffffff', 'white'):
            # white text: on a surface of its own rule, X3's text white (or plain white on a mid-tone colour fill);
            # with no surface of its own it sits on an ancestor's, so it follows that surface through --on-slab
            r = TX if ctx['bg'] in ('paper', 'slab', 'tint') else v if ctx['bg'] == 'other' else 'var(--on-slab)'
        else: r = map_mix_up_dn(v) or map_colour(v, TEXT_MAP) or v
    elif lh == 'background-color':
        if ctx.get('sel'): r = S3                           # X3's pressed state: its raised surface
        elif ctx.get('stem') and n == 'var(--ink)': r = LINE  # a diagram stem: the line colour, like its bracket
        elif n == 'var(--ink)' and ctx['chip']: r = S3
        elif ctx.get('logo') and n in ('#fff', '#ffffff', 'white'): r = v     # logo tiles stay white (logos are drawn for it)
        elif n == 'color-mix(insrgb,#fff70%,transparent)': r = 'color-mix(in srgb,%s 70%%,transparent)' % S3
        else: r = tint(map_colour(v, BG_MAP) or v)
    elif lh == 'background-image':
        r = rays(tint(map_stops(v, BG_MAP)))
    elif lh in ('fill', 'stroke'):
        r = map_colour(v, FILL_MAP) or v
    elif lh == '--rki':
        r = ONY if n == 'var(--ink)' else v
    elif lh == '--c':
        r = LINE if n == '#d8d2c4' else v
    else:
        r = v
    return None if norm(r) == n else r

# ---------------------------------------------------------------- selectors
ROOTCLS = re.compile(r'^(html\b|:root\b)|\.(x2|x3|x4|pt|rm)(?![\w-])')

def specificity(sel):
    a = b = c = 0
    i, s = 0, sel
    while i < len(s):
        ch = s[i]
        if ch == '#':
            a += 1; i += 1
            while i < len(s) and (s[i].isalnum() or s[i] in '-_'): i += 1
        elif ch == '.':
            b += 1; i += 1
            while i < len(s) and (s[i].isalnum() or s[i] in '-_'): i += 1
        elif ch == '[':
            b += 1; d = 0
            while i < len(s):
                if s[i] == '[': d += 1
                elif s[i] == ']':
                    d -= 1
                    if d == 0: i += 1; break
                i += 1
        elif ch == ':':
            pe = s.startswith('::', i)
            i += 2 if pe else 1
            j = i
            while j < len(s) and (s[j].isalnum() or s[j] in '-_'): j += 1
            name = s[i:j].lower(); i = j
            arg = None
            if i < len(s) and s[i] == '(':
                d, k = 0, i
                while k < len(s):
                    if s[k] == '(': d += 1
                    elif s[k] == ')':
                        d -= 1
                        if d == 0: break
                    k += 1
                arg = s[i + 1:k]; i = k + 1
            if pe or name in ('before', 'after', 'first-line', 'first-letter'):
                c += 1
            elif name == 'where':
                pass
            elif name in ('is', 'not', 'has', 'matches', '-webkit-any'):
                sp = max((specificity(x) for x in split_top(arg or '', ',')), default=(0, 0, 0))
                a, b, c = a + sp[0], b + sp[1], c + sp[2]
            elif name in ('nth-child', 'nth-last-child') and arg and ' of ' in arg:
                sp = max(specificity(x) for x in split_top(arg.split(' of ', 1)[1], ','))
                a, b, c = a + sp[0], b + 1 + sp[1], c + sp[2]
            else:
                b += 1
        elif ch.isalpha() or ch == '_':
            c += 1
            while i < len(s) and (s[i].isalnum() or s[i] in '-_'): i += 1
        else:
            i += 1
    return (a, b, c)

def first_compound(sel):
    d = 0
    for i, ch in enumerate(sel):
        if ch in '([': d += 1
        elif ch in ')]': d -= 1
        elif d == 0 and (ch.isspace() or ch in '>+~'): return sel[:i], sel[i:]
    return sel, ''

def scope(sel):
    head, tail = first_compound(sel.strip())
    if ROOTCLS.search(head):
        if re.match(r'html\b', head): return 'html:where(.x4)' + head[4:] + tail
        return head + ':where(.x4)' + tail
    return ':where(html.x4) ' + sel.strip()

def x3_only(sel):
    head, _ = first_compound(sel.strip())
    return bool(re.search(r'\.x3(?![\w-])', head))

# ---------------------------------------------------------------- read every rule, in source order
def rules_of(css):
    out = []
    def walk(rs, media):
        for r in rs:
            if r.type == 'qualified-rule':
                sels = [x for x in split_top(tinycss2.serialize(r.prelude).strip(), ',') if x]
                sels = [x for x in sels if not x3_only(x)]
                if not sels: continue
                decls = [(d.name, tinycss2.serialize(d.value).strip(), d.important)
                         for d in tinycss2.parse_blocks_contents(r.content, skip_whitespace=True, skip_comments=True)
                         if d.type == 'declaration']
                out.append({'media': media, 'sels': sels, 'decls': decls, 'spec': {specificity(x) for x in sels}})
            elif r.type == 'at-rule' and r.lower_at_keyword in ('media', 'supports') and r.content is not None:
                walk(tinycss2.parse_rule_list(r.content, skip_whitespace=True, skip_comments=True),
                     media + ('@%s %s' % (r.lower_at_keyword, tinycss2.serialize(r.prelude).strip()),))
            elif r.type == 'at-rule' and r.lower_at_keyword == 'keyframes':
                out.append({'keyframes': tinycss2.serialize(r.prelude).strip(), 'body': r.content, 'media': media})
    for css_text in css:
        walk(tinycss2.parse_stylesheet(css_text, skip_whitespace=True, skip_comments=True), ())
    return out

def keyframes_copy(R):
    """keyframes cannot be scoped; skin-x4.css only ships in X4, so a same-name redefinition (later wins) is enough"""
    changed = False
    out = []
    for kr in tinycss2.parse_rule_list(R['body'], skip_whitespace=True, skip_comments=True):
        if kr.type != 'qualified-rule': continue
        ds = []
        for d in tinycss2.parse_blocks_contents(kr.content, skip_whitespace=True, skip_comments=True):
            if d.type != 'declaration': continue
            v = tinycss2.serialize(d.value).strip()
            nv = map_shadow(v) if d.lower_name == 'box-shadow' else v
            changed |= nv != v
            ds.append('%s:%s' % (d.name, nv))
        out.append('%s{%s}' % (tinycss2.serialize(kr.prelude).strip(), ';'.join(ds)))
    return '@keyframes %s{%s}' % (R['keyframes'], ''.join(out)) if changed else None

# ---------------------------------------------------------------- generate
def is_sel(R):
    if not all(SELECTED.search(x) for x in R['sels']): return False
    c = [norm(longhands(n, v).get('background-color', '')) for n, v, _ in R['decls']]
    return any(x in SLABS or x == 'var(--ink)' for x in c)

def ctx_of(R):
    bg = rule_bg(R['decls'])
    if is_sel(R): bg = 'sel'
    ink_bg = any(longhands(n, v).get('background-color', '').strip() == 'var(--ink)' for n, v, _ in R['decls'])
    return {'bright': bg in ('y', 'gr'), 'sel': bg == 'sel', 'bg': bg, 'chip': ink_bg and any(n.lower() == 'color' for n, _, _ in R['decls']),
            'logo': all(re.search(r'\.co-mark\b[^ >+~]*$', x) for x in R['sels']),
            'stem': all(x in STEMS for x in R['sels'])}

def generate():
    rules = rules_of(x2_css())
    emit = {}      # rule index -> {longhand: (value, important)}
    kf = []
    for i, R in enumerate(rules):
        if 'keyframes' in R:
            k = keyframes_copy(R)
            if k: kf.append(k)
            continue
        ctx = ctx_of(R)
        bg = 'slab' if ctx['sel'] else rule_bg(R['decls'])
        has_color = any(n.lower() == 'color' for n, _, _ in R['decls'])
        if ctx['logo'] and any(norm(longhands(n, v).get('background-color', '')) in ('#fff', '#ffffff', 'white') for n, v, _ in R['decls']):
            bg = 'y'             # a white logo tile stays white: dark text on it, like on yellow
        for name, v, imp in R['decls']:
            for lh, val in longhands(name, v).items():
                nv = map_decl(lh, val, ctx)
                if nv is not None: emit.setdefault(i, {})[lh] = (nv, imp)
        e = emit.setdefault(i, {})
        same = [X3_SAME[x] for x in R['sels'] if x in X3_SAME]
        if same:                 # X3's own colours for this element, on the longhands X2's rule sets
            for name, v, imp in R['decls']:
                for lh in longhands(name, v):
                    if lh in same[0]: e[lh] = (same[0][lh], imp)
        if bg in ('y', 'gr'):    # yellow / green / red stay bright in X3's palette: dark ink and dark text on them
            dark = INK_ON_Y if bg == 'y' else INK_ON_GR
            for k, val in zip(INK_KEYS + SLAB_KEYS, dark + dark[:3]): e.setdefault(k, (val, False))
            for k, val in zip(('--up', '--dn'), UPDN_ON_YEL if bg == 'y' else (ONY, ONY)): e.setdefault(k, (val, False))
            if not has_color: e['color'] = ('var(--ink)', False)
        elif bg in ('paper', 'tint', 'slab', 'foil', 'win'):   # paper, washes, navy, foil and wins turn dark: light ink
            for k, val in zip(INK_KEYS + ('--up', '--dn'), INK_LIGHT + UPDN_LIGHT): e.setdefault(k, (val, False))
            if bg == 'foil': e['--x4-ring'] = (YEL, False)
            if bg == 'win': e['--x4-ring'] = (YEL_L, False)
            if bg == 'slab':
                for k, val in zip(SLAB_KEYS, SLAB_LIGHT): e.setdefault(k, (val, False))
        elif bg == 'clear':      # a fill removed again (".cc b.u{background:none}"): the text tokens come from the parent
            for k in INK_KEYS + SLAB_KEYS + ('--up', '--dn'): e.setdefault(k, ('inherit', False))
        if not e: del emit[i]
    # cascade closure: a later rule of equal specificity that set the same longhand must stay later
    declared = []
    for R in rules:
        d = {}
        if 'keyframes' not in R:
            for name, v, imp in R['decls']:
                for lh, val in longhands(name, v).items(): d[lh] = (val, imp)
        declared.append(d)
    work = [(i, lh) for i in emit for lh in emit[i]]
    seen = set(work)
    while work:
        i, lh = work.pop()
        imp = emit[i][lh][1]
        for j in range(i + 1, len(rules)):
            R = rules[j]
            if 'keyframes' in R or lh not in declared[j] or (j, lh) in seen: continue
            if declared[j][lh][1] != imp or not (rules[i]['spec'] & R['spec']): continue
            val = declared[j][lh][0]
            nv = map_decl(lh, val, ctx_of(R))
            emit.setdefault(j, {})[lh] = (nv if nv is not None else (val if val else 'initial'), imp)
            seen.add((j, lh)); work.append((j, lh))
    # write, in source order, consecutive rules of the same media in one block
    lines, cur, buf = [], None, []
    def flush():
        if not buf: return
        if cur:
            o = ''.join('%s{' % m for m in cur)
            lines.append(o + ''.join(buf) + '}' * len(cur))
        else:
            lines.extend(buf)
    for i in sorted(emit):
        R = rules[i]
        body = ';'.join('%s:%s%s' % (lh, v, ' !important' if imp else '') for lh, (v, imp) in emit[i].items())
        txt = '%s{%s}' % (','.join(scope(s) for s in R['sels']), body)
        if R['media'] != cur:
            flush(); buf = []; cur = R['media']
        buf.append(txt)
    flush()
    return '\n'.join(kf + lines), len(emit), sum(len(v) for v in emit.values())

if __name__ == '__main__':
    gen, nr, nd = generate()
    old = open(SKIN).read()
    a, b = old.index(BEGIN), old.index(END)
    new = old[:a] + BEGIN + '\n' + gen + '\n' + old[b:]
    open(SKIN, 'w').write(new)
    print('skin-x4.css: %d rules, %d declarations generated, %d bytes' % (nr, nd, len(new)))
