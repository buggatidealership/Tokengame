def map_rgba_overlay(c):
    """dark navy overlays on posters -> the graphite page colour, same alpha"""
    m = re.fullmatch(r'rgba\((10,12,24|6,10,26|8,12,30),([\d.]+)\)', norm(c))
    return 'rgba(29,28,26,%s)' % m.group(2) if m else None

def map_mix_up_dn(c):
    """color-mix(var(--up) 80%,#000): X2 darkened the up / down text for paper; on the dark it is the plain colour"""
    m = re.fullmatch(r'color-mix\(insrgb,var\(--(up|dn)\)\d+%,#000\)', norm(c))
    return 'var(--%s)' % m.group(1) if m else None

def map_colour(c, table):
    n = norm(c)
    if n in table: return table[n]
    return map_rgba_overlay(c) if table is BG_MAP else None

def map_stops(v, table):
    """map every colour inside gradients / color-mix / data URIs (backgrounds)"""
    def sub_fn(m):
        r = map_colour(m.group(0), table)
        return r if r else m.group(0)
    out = re.sub(r'rgba?\([^()]*\)|#[0-9a-fA-F]{3,8}\b|var\(--slab,#101a3a\)', sub_fn, v)
    for a, b in CHEVRON.items(): out = out.replace(a, b)
    return out

# ---------------------------------------------------------------- per property
def map_shadow(v):
    layers = split_top(v, ',')
    out = []
    for L in layers:
        parts = split_top(L, ' ')
        inset = 'inset' in parts
        cols = [p for p in parts if p != 'inset' and not LEN.match(p)]
        lens = [p for p in parts if LEN.match(p)]
        if len(cols) == 1 and norm(cols[0]) in INK:
            off = [float(re.match(r'-?[\d.]+', x).group(0)) for x in lens[:2]] if len(lens) >= 2 else [0, 0]
            new = LINE if inset or (off[0] == 0 and off[1] == 0) else SHADOW
            L = ' '.join(new if p == cols[0] else p for p in parts)
        out.append(L)
    return ','.join(out)

def map_text_shadow(v):
    layers = split_top(v, ',')
    inks = [L for L in layers if any(norm(p) in INK for p in split_top(L, ' '))]
    if not inks: return v
    outline = len(layers) >= 4 and len(inks) == len(layers)
    def one(L):
        parts = split_top(L, ' ')
        return ' '.join((LINE if outline else SHADOW) if norm(p) in INK else p for p in parts)
    return ','.join(one(L) for L in layers)

def map_line_colour(c):
    """a border / outline colour"""
    n = norm(c)
    if n in INK: return LINE
    if n in ('var(--field2)', 'var(--field)', 'var(--card)'): return HAIR
    return c

def border_colour_of(v):
    parts = split_top(v, ' ')
    cols = [p for p in parts if is_colourish(p)]
    return cols[0] if cols else 'currentcolor'

# longhands each declaration sets that this generator may touch
SIDES = ('top', 'right', 'bottom', 'left')
def longhands(name, v):
    """{longhand: X2 value} for the colour longhands a declaration sets ('' = reset to initial)"""
    n = name.lower()
    if n.startswith('--'): return {n: v}
    if n in ('color', 'fill', 'stroke', 'stop-color', 'box-shadow', 'text-shadow', 'caret-color', 'filter',
             '-webkit-text-fill-color', 'text-decoration-color', 'accent-color', 'background-color', 'background-image',
             'outline-color', 'column-rule-color', '-webkit-text-stroke-color'):
        return {n: v}
    if n == 'background':
        layers = split_top(v, ',')
        last = split_top(layers[-1], ' ')
        col = [p for p in last if is_colourish(p) and not norm(p).startswith(('var(--foil', 'var(--win', 'var(--hazard', 'var(--bg'))]
        # one image per layer (a gradient, a url, or a token that holds one); 'none' for a layer without one
        img = lambda L: next((p for p in split_top(L, ' ') if re.match(r'(repeating-)?(linear|radial|conic)-gradient\(|url\(|var\(--(foil|win|hazard|bg)\b', p)), 'none')
        imgs = [img(L) for L in layers]
        return {'background-color': col[0] if col else 'transparent', 'background-image': ','.join(imgs) if any(i != 'none' for i in imgs) else 'none'}
    if n == 'border' or n == 'border-color':
        if n == 'border-color':
            ps = split_top(v, ' ')
            ps = ps * 4 if len(ps) == 1 else ps * 2 if len(ps) == 2 else ps + [ps[1]] if len(ps) == 3 else ps[:4]
            return {'border-%s-color' % s: ps[i] for i, s in enumerate(SIDES)}
        c = border_colour_of(v)
        return {'border-%s-color' % s: c for s in SIDES}
    m = re.fullmatch(r'border-(top|right|bottom|left)(-color)?', n)
    if m: return {'border-%s-color' % m.group(1): v if m.group(2) else border_colour_of(v)}
    if n == 'outline': return {'outline-color': border_colour_of(v)}
    if n == 'text-decoration': return {'text-decoration-color': border_colour_of(v) if any(is_colourish(p) for p in split_top(v, ' ')) else 'currentcolor'}
    if n == '-webkit-text-stroke': return {'-webkit-text-stroke-color': border_colour_of(v)}
    return {}

