def rule_bg(decls):
    """'y' / 'gr' (stays bright), 'paper' / 'slab' / 'tint' (turns dark), or None"""
    bg = None
    for name, v, imp in decls:
        lh = longhands(name, v)
        if 'background-color' not in lh and 'background-image' not in lh: continue
        c, im = norm(lh.get('background-color', 'transparent')), norm(lh.get('background-image', 'none'))
        if c in BRIGHT_Y: bg = 'y'
        elif c in BRIGHT_GR: bg = 'gr'
        elif c in PAPER: bg = 'paper'
        elif c in SLABS: bg = 'slab'
        elif im == 'var(--win-grad)': bg = 'win'      # X2's yellow shimmer: dark C's gold foil (dark text on it)
        elif im == 'var(--foil-grad)': bg = 'foil'    # X2's rainbow foil (#1): dark C's gold foil (dark text on it)
        elif im in TINT_IMG or re.match(r'color-mix\(insrgb,var\(--(yel|ez-gold|ez-green|ez-red|red|grn|mc)\)\d+%,var\(--(card|field)\)\)', c):
            bg = 'tint'
        elif c in ('transparent', 'none') and im == 'none':
            bg = 'clear'
        elif c not in ('inherit', 'initial', 'unset', 'currentcolor', 'var(--ink)') and not c.startswith('rgba(0,0,0'):
            bg = 'other'
    return bg

def tint(v):
    """X2's colour washes over paper (14-70%) would turn olive and muddy on the graphite: a dark-mode strength instead
    (gold 10%, the board's tint for the pot column; the other hues half, at least 8%)"""
    def f(m):
        k, n = m.group(1), int(m.group(2))
        n = 10 if k in ("yel", "ez-gold") else max(8, round(n / 2))
        return 'color-mix(in srgb,var(--%s) %d%%,var(--%s))' % (k, n, m.group(3))
    v = re.sub(r'color-mix\(in srgb,\s*var\(--(yel|ez-gold|ez-green|ez-red|red|grn)\)\s+(\d+)%,\s*var\(--(card|field)\)\)', f, v)
    # the stat panels' key-colour wash (--mc: blue, green, gold, violet at 13-16%) is a heavy cast on the dark: 6%
    v = re.sub(r'color-mix\(in srgb,\s*var\(--mc\)\s+\d+%,\s*var\(--(card|field)\)\)', r'color-mix(in srgb,var(--mc) 6%,var(--\1))', v)
    # X2's pale blue panel (the 31% "operations" box): no blue in dark C, the raised surface instead
    return re.sub(r'color-mix\(in srgb,\s*#2f7fe0\s+\d+%,\s*var\(--card\)\)', 'var(--x5-s3)', v)

def rays(v):
    """the sunburst on sealed and upcoming rounds: the board keeps X2's rays in the dark C gold (var(--yel)) on the
    card colour, so nothing changes here (X4 dims them to 30%)"""
    return v

def map_decl(lh, v, ctx):
    """dark C value for one colour longhand, or None when it does not change"""
    n = norm(v)
    if lh == 'box-shadow':
        r = map_shadow(v)
    elif lh == 'text-shadow':
        r = map_text_shadow(v)
    elif lh.endswith('-color') and (lh.startswith('border') or lh.startswith('outline') or lh.startswith('column-rule')):
        r = map_line_colour(v)
    elif lh in ('color', '-webkit-text-fill-color', 'caret-color'):
        if ctx.get('sel'): r = v if n == 'var(--yel)' else TX      # the pressed state: light text (gold stays)
        elif ctx['bright'] and (n in DARK_TEXT or n in ('var(--on-slab)', 'var(--on-slab2)', 'var(--on-slab3)')): r = 'var(--ink)'
        elif ctx.get('chip') and n in ('#fff', '#ffffff', 'white'): r = TX     # white on an ink chip: the chip is the raised surface
        elif n in ('#fff', '#ffffff', 'white'):
            # white text: on a surface of its own rule, the light text (or plain white on a mid-tone colour fill);
            # with no surface of its own it sits on an ancestor's, so it follows that surface through --on-slab
            r = TX if ctx['bg'] in ('paper', 'slab', 'tint') else v if ctx['bg'] == 'other' else 'var(--on-slab)'
        else: r = map_mix_up_dn(v) or map_colour(v, TEXT_MAP) or v
    elif lh == 'background-color':
        if ctx.get('sel'): r = S3                           # the pressed state: the raised surface
        elif ctx.get('stem') and n == 'var(--ink)': r = LINE  # a diagram stem: the line colour, like its bracket
        elif n == 'var(--ink)' and ctx['chip']: r = S3
        elif ctx.get('logo') and n in ('#fff', '#ffffff', 'white'): r = v     # logo tiles stay white (logos are drawn for it)
        elif n == 'color-mix(insrgb,#fff70%,transparent)': r = 'color-mix(in srgb,%s 70%%,transparent)' % S3
        else: r = tint(map_colour(v, BG_MAP) or v)
    elif lh == 'background-image':
        r = rays(tint(map_stops(v, BG_MAP)))
    elif lh in ('fill', 'stroke'):
        r = map_colour(v, FILL_MAP) or v
    elif lh == '--rki':
        r = ONY if n == 'var(--ink)' else v
    elif lh == '--c':
        r = LINE if n == '#d8d2c4' else v
    else:
        r = v
    return None if norm(r) == n else r

