// node scripts/build.mjs [--check]
// Writes src/names.js (ticker -> company name) and src/static.js (public/* as strings, so the Worker and the Node harness import
// the same files). --check exits 1 if either is out of date (run by `npm test`).
// Names come from the repo, nothing typed here: ez/tools/concepts/dopa/prep-close.js CO (Season 2 so far), the terminal's Season 2
// calendar (ez/tools/concepts/hyperdash/index.html, var S2) and ez/ez-data.js TICKERS (Season 1). First source wins.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.resolve(HERE, '..'), EZ = path.resolve(ROOT, '../..');
const check = process.argv.includes('--check');
const lit = (src, re, what) => { const m = src.match(re); if (!m) throw new Error('could not find ' + what); return vm.runInNewContext('(' + m[1] + ')', {}) };

const names = {};
const add = (t, n, src) => { t = String(t).toUpperCase(); if (n && !names[t]) names[t] = { n, src } };
const pc = fs.readFileSync(path.join(EZ, 'tools/concepts/dopa/prep-close.js'), 'utf8');
for (const [t, v] of Object.entries(lit(pc, /const CO = (\{[^;]*?\});/, 'prep-close.js CO'))) add(t, v[0], 'prep-close.js CO');
const term = fs.readFileSync(path.join(EZ, 'tools/concepts/hyperdash/index.html'), 'utf8');
for (const r of lit(term, /var S2=(\[[^;]*?\]);/, 'terminal S2')) add(r[0], r[1], 'terminal S2');
const ezd = fs.readFileSync(path.join(EZ, 'ez-data.js'), 'utf8');
for (const [t, n] of Object.entries(lit(ezd, /var TICKERS=(\{[^;]*?\});/, 'ez-data.js TICKERS'))) add(t, n, 'ez-data.js TICKERS');

const sorted = Object.keys(names).sort();
const namesJs = `// GENERATED by scripts/build.mjs from prep-close.js CO, the terminal's S2 calendar and ez-data.js TICKERS. Do not edit.\n` +
  `// A ticker missing here shows as the ticker itself in alerts (and the watcher logs NO_NAME).\n` +
  `export const NAMES = ${JSON.stringify(Object.fromEntries(sorted.map(t => [t, names[t].n])), null, 0).replace(/","/g, '",\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, '\n}')};\n`;

const pub = f => fs.readFileSync(path.join(ROOT, 'public', f), 'utf8');
const staticJs = `// GENERATED by scripts/build.mjs from public/. Do not edit; edit public/* and run \`npm run build\`.\n` +
  `export const SW_JS = ${JSON.stringify(pub('sw.js'))};\n` +
  `export const MANIFEST = ${JSON.stringify(pub('manifest.webmanifest'))};\n` +
  `export const CLIENT_JS = ${JSON.stringify(pub('client.js'))};\n` +
  `export const TRY_HTML = ${JSON.stringify(pub('try.html'))};\n`;

let stale = 0;
for (const [f, body] of [['src/names.js', namesJs], ['src/static.js', staticJs]]) {
  const p = path.join(ROOT, f), cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '';
  if (cur === body) continue;
  if (check) { console.error(`STALE ${f}: run npm run build`); stale++ } else { fs.writeFileSync(p, body); console.log('wrote ' + f) }
}
if (check && stale) process.exit(1);
if (!check) console.log(`${sorted.length} company names (${['prep-close.js CO', 'terminal S2', 'ez-data.js TICKERS'].map(s => s + ' ' + sorted.filter(t => names[t].src === s).length).join(', ')})`);
else console.log('build: names.js and static.js are current');
